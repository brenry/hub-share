test('the Stage zooms only its image; Ctrl+0 fits; the grid scrolls only itself', async ({ page }) => {
  await open(page, '/media', new FakeHub(), apiState())
  await page.locator('[data-stage-img]').waitFor()
  const img = page.locator('[data-stage-img]')
  const before = await img.evaluate(el => el.style.transform)
  const stage = (await page.locator('[data-region="stage"]').boundingBox())!
  await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2)
  await page.mouse.wheel(0, -400)
  await expect.poll(() => img.evaluate(el => el.style.transform)).not.toBe(before)
  expect(await rootScroll(page)).toEqual(ZERO)
  await page.keyboard.press('Control+0')
  await expect.poll(() => img.evaluate(el => el.style.transform)).toBe(before)
  const grid = page.locator('[data-scroll="media-grid"]')
  const g = (await grid.boundingBox())!
  await page.mouse.move(g.x + g.width / 2, g.y + g.height / 2)
  await page.mouse.wheel(0, 500)
  await expect.poll(() => grid.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect(await rootScroll(page)).toEqual(ZERO)
})

test('a new generation lands first and shows on the Stage, without breaking a multi-selection; in a group view it only says so', async ({ page }) => {
  const { hub } = await open(page, '/media', new FakeHub(), apiState())
  await tiles(page).first().waitFor()
  const item = (n: number, group = '') => ({ id: `out/2026-10-10/${group ? group + '/' : ''}new_${n}.png`, kind: 'image', url: `/files/out/new_${n}.png`, thumb: `/thumbs/out/new_${n}.png/336`,
    w: 1024, h: 1024, created: 1791569999, job: 'j1' })
  hub.broadcast('generation', { item: item(1) }, 'media')
  await expect(tiles(page).first()).toHaveAttribute('data-item', 'out/2026-10-10/new_1.png')
  await expect(page.locator('[data-stage-img]')).toHaveAttribute('src', '/files/out/new_1.png')
  await expect(page.locator('[data-region="count"]')).toHaveText('1 / 61')
  await tiles(page).nth(1).click()
  await tiles(page).nth(2).click({ modifiers: ['Control'] })
  hub.broadcast('generation', { item: item(2) }, 'media')
  await expect(page.getByText('New generation')).toBeVisible()
  await expect(page.locator('[data-item][aria-selected="true"]')).toHaveCount(2)
  await row(page, 'temp/Character 17').click()
  hub.broadcast('generation', { item: item(3, 'Group 2') }, 'media')
  await expect(page.getByText('New generation').last()).toBeVisible()
  await expect(tiles(page).first()).not.toHaveAttribute('data-item', /new_3/)
  await expect(row(page, 'temp/Group 2')).toContainText('8')
})

