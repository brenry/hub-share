test('the plan: Stage alone on the left; two tiles per row over one bar in the bottom right; the organizer; nothing of the old bars', async ({ page }) => {
  await open(page, '/media', new FakeHub(), apiState())
  await tiles(page).first().waitFor()
  await expect(page.locator('[data-region="topbar"]')).toHaveCount(0)
  await expect(page.getByText('Media', { exact: true })).toHaveCount(0)
  for (const gone of ['Keep', 'Kept generations', 'Trash', 'Discard', 'Send to Workspace', 'Follow new generations']) await expect(page.getByText(gone)).toHaveCount(0)
  await expect(page.getByRole('button', { name: /reference \d/i })).toHaveCount(0)
  await expect(page.locator('[data-region="bar"]')).not.toContainText(/generate/i)
  await expect(page.locator('[data-region="generate"]')).toHaveCount(1)
  await expect(page.locator('[data-region="title"]')).toHaveCount(0)
  await expect(page.locator('[data-region="count"]')).toHaveText('1 / 60')
  await expect(page.locator('[data-live]')).toHaveText('Live')
  const bar = (await page.locator('[data-region="bar"]').boundingBox())!
  const view = page.viewportSize()!
  expect(Math.round(bar.x + bar.width)).toBe(view.width)
  expect(Math.round(bar.y + bar.height)).toBe(view.height)
  await expect(page.locator('[data-region="bar"] [data-region="launch"]')).toHaveCount(0)
  await expect(page.locator('[data-region="bar"] button')).toHaveCount(7)
  await expect(row(page, 'temp')).toContainText('Temp')
  await expect(row(page, 'temp/Character 17')).toContainText('Character 17')
  await expect(row(page, 'temp/Group 2')).toContainText('Group 2')
  await expect(row(page, 'fav')).toContainText('Favorites')
  await expect(row(page, 'drive:')).toContainText('ComfyUI')
  await expect(row(page, 'drive:image')).toContainText('image')
  await expect(row(page, 'drive:video')).toContainText('video')
  const [a, b, c] = await Promise.all([0, 1, 2].map(i => tiles(page).nth(i).boundingBox()))
  expect(Math.abs(a!.y - b!.y)).toBeLessThan(1)
  expect(c!.y).toBeGreaterThan(a!.y + a!.height - 1)
  expect(Math.abs(c!.x - a!.x)).toBeLessThan(1)
  expect(Math.abs(a!.width - a!.height)).toBeLessThan(1.5)
  const stage = (await page.locator('[data-region="stage"]').boundingBox())!
  expect(stage.x).toBe(0)
  expect(stage.y).toBe(0)
})

test('right-click: the menu sends to references, favorites, moves, deletes last; the window\'s own menu stays out', async ({ page }) => {
  const { hub, media, st } = await twoWindows(page)
  await media.evaluate(() => { (window as unknown as { prevented: boolean[] }).prevented = []; window.addEventListener('contextmenu', e => (window as unknown as { prevented: boolean[] }).prevented.push(e.defaultPrevented)) })
  await tiles(media).nth(1).click()
  await tiles(media).nth(2).click({ modifiers: ['Control'] })
  await tiles(media).nth(2).click({ button: 'right' })
  const menu = media.getByRole('menu', { name: 'Image' })
  await expect(menu.getByRole('menuitem')).toHaveText([/Add 2 as references/, /Favorite/, /Add to Characters/, /Delete 2/])
  await expect(menu.getByText(/Move to/)).toHaveCount(0)
  expect(await media.evaluate(() => (window as unknown as { prevented: boolean[] }).prevented)).toEqual([true])
  await menu.getByRole('menuitem', { name: /Add 2 as references/ }).click()
  await expect(media.getByText('2 added to Generate Image · References 2–3')).toBeVisible()
  expect(hub.got.find(e => e.t === 'received')!.d).toMatchObject({ placed: [{ socket: 'reference_2' }, { socket: 'reference_3' }] })
  await tiles(media).nth(0).click({ button: 'right' })
  const top = menu.getByRole('menuitem', { name: /Add as reference/ })
  await expect(top).toBeEnabled()
  await top.hover()
  const slots = media.getByRole('menu', { name: /Add as reference/ })
  await expect(slots.getByRole('menuitem')).toHaveText(['Replace Reference 1', 'Replace Reference 2', 'Replace Reference 3'])
  expect((await slots.boundingBox())!.x + (await slots.boundingBox())!.width).toBeLessThanOrEqual((await top.boundingBox())!.x)
  await slots.getByRole('menuitem', { name: 'Replace Reference 2' }).click()
  await expect.poll(() => hub.got.filter(e => e.t === 'received').length).toBe(2)
  expect(hub.got.filter(e => e.t === 'received')[1]!.d).toMatchObject({ placed: [{ socket: 'reference_2' }] })
  await tiles(media).nth(1).click()
  await tiles(media).nth(2).click({ modifiers: ['Control'] })
  await tiles(media).nth(2).click({ button: 'right' })
  await menu.getByRole('menuitem', { name: /references/ }).hover()
  await expect(media.getByRole('menu', { name: /references/ })).toHaveCount(0)
  await media.keyboard.press('Escape')
  await tiles(media).nth(0).click()
  await tiles(media).nth(0).click({ button: 'right' })
  const favored = st.media[0]!.id
  await menu.getByRole('menuitem', { name: 'Favorite' }).click()
  await expect(media.getByText('Favorite', { exact: true })).toBeVisible()
  expect(st.media[0]!.id).toBe(`out/2026-10-09/Favorites/${favored.split('/').pop()}`)
  await expect(tiles(media).nth(0)).toHaveAttribute('aria-selected', 'true')
  await tiles(media).nth(0).click({ button: 'right' })
  await expect(menu.getByRole('menuitem', { name: 'Remove favorite' })).toBeVisible()
  await media.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(tiles(media).nth(0).locator('[aria-label="Favorite"]')).toBeVisible()
})

