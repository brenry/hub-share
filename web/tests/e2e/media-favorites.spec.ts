// Favorite folders: Drive folders pinned under Favorites from their right-click menu — a list of names, nothing moved.
import { expect, test } from '@playwright/test'
import { FakeHub } from './fixtures/controller'
import { apiState } from './fixtures/api'
import { row, tiles } from './fixtures/mediaPage'
import { open } from './helpers'

test('favorite folders: a Drive folder\'s right-click pins it under Favorites by name, ten deep or not; nothing moves; images have no such line', async ({ page }) => {
  const st = apiState()
  st.drive.folders['image/portraits']!.dirs = ['closeups']
  st.drive.folders['image/portraits/closeups'] = { dirs: [], items: [] }
  await open(page, '/media', new FakeHub(), st)
  await tiles(page).first().waitFor()
  await expect(row(page, 'fav')).not.toHaveAttribute('aria-expanded', /./)
  await row(page, 'drive:image').click()
  await row(page, 'drive:image/portraits').click({ button: 'right' })
  const folderMenu = page.getByRole('menu', { name: 'Folder' })
  await expect(folderMenu.getByRole('menuitem').first()).toHaveText('Add to Favorites')
  await folderMenu.getByRole('menuitem', { name: 'Add to Favorites' }).click()
  await expect(page.getByText('Added to Favorites')).toBeVisible()
  expect(st.calls.find(c => c.method === 'POST' && c.path === '/api/media/favorite-folders')?.body).toEqual({ path: 'image/portraits', on: true })
  await expect(row(page, 'fav')).toHaveAttribute('aria-expanded', 'true')
  const pinned = row(page, 'fav:image/portraits')
  await expect(pinned).toHaveText(/portraits/)
  expect((await pinned.boundingBox())!.y).toBeLessThan((await row(page, 'drive:').boundingBox())!.y)
  await expect(row(page, 'drive:image/portraits')).toBeVisible()
  await row(page, 'drive:video').click({ button: 'right' })
  await folderMenu.getByRole('menuitem', { name: 'Add to Favorites' }).click()
  await expect(row(page, 'fav:video')).toBeVisible()
  await expect(page.locator('[data-row^="fav:"]')).toHaveText([/portraits/, /video/])
  await row(page, 'drive:').click({ button: 'right' })
  await expect(folderMenu.getByRole('menuitem', { name: /Favorites/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await pinned.click()
  await expect(tiles(page)).toHaveCount(3)
  await expect(pinned).toHaveAttribute('aria-selected', 'true')
  await expect(pinned).toContainText('3')
  await expect(row(page, 'fav:image/portraits>image/portraits/closeups')).toBeVisible()
  await row(page, 'fav:image/portraits>image/portraits/closeups').click()
  await expect(tiles(page)).toHaveCount(0)
  await expect(row(page, 'fav:video')).not.toHaveAttribute('aria-expanded', /./)
  await pinned.click({ button: 'right' })
  await expect(folderMenu.getByRole('menuitem')).toHaveText(['Remove from Favorites'])
  await page.keyboard.press('Escape')
  expect(st.calls.filter(c => c.path.startsWith('/api/media/move') || c.path.startsWith('/api/media/drive/move') || c.path === '/api/media/favorite')).toEqual([])
  await row(page, 'temp').click()
  await tiles(page).first().click({ button: 'right' })
  await expect(page.getByRole('menu', { name: 'Image' }).getByRole('menuitem', { name: /Favorites/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await row(page, 'drive:image/portraits').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Rename' }).click()
  await page.getByLabel('Folder name').fill('faces')
  await page.keyboard.press('Enter')
  await expect(row(page, 'fav:image/faces')).toHaveText(/faces/)
  await row(page, 'fav:image/faces').click({ button: 'right' })
  await folderMenu.getByRole('menuitem', { name: 'Remove from Favorites' }).click()
  await expect(page.getByText('Removed from Favorites')).toBeVisible()
  await expect(row(page, 'fav:image/faces')).toHaveCount(0)
  await expect(row(page, 'drive:image/faces')).toBeVisible()
  await expect(row(page, 'fav:video')).toBeVisible()
})
